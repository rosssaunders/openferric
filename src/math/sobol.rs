#[derive(Debug, Clone)]
pub struct SobolSequence {
    dimensions: usize,
    index: u64,
    x: Vec<u64>,
    directions: Vec<[u64; 64]>,
    scramblers: Vec<u64>,
}

impl SobolSequence {
    /// Creates a Sobol sequence over `dimensions` coordinates.
    ///
    /// `seed == 0` yields the canonical (unscrambled) Joe-Kuo Sobol sequence;
    /// any other seed applies a deterministic per-dimension digital shift.
    ///
    /// # Panics
    ///
    /// Panics if `dimensions` is outside `[1, SOBOL_MAX_DIMENSIONS]`.
    pub fn new(dimensions: usize, seed: u64) -> Self {
        assert!(
            (1..=SOBOL_MAX_DIMENSIONS).contains(&dimensions),
            "Sobol dimensions must be in [1, {SOBOL_MAX_DIMENSIONS}], got {dimensions}"
        );

        let mut directions = Vec::with_capacity(dimensions);
        let mut scramblers = Vec::with_capacity(dimensions);

        for dim in 0..dimensions {
            directions.push(build_direction_numbers(dim));
            let scrambler = if seed == 0 {
                0
            } else {
                splitmix64(seed ^ ((dim as u64 + 1) << 32))
            };
            scramblers.push(scrambler);
        }

        Self {
            dimensions,
            index: 0,
            x: vec![0_u64; dimensions],
            directions,
            scramblers,
        }
    }

    #[inline]
    pub fn dimensions(&self) -> usize {
        self.dimensions
    }

    /// Advances the sequence and writes the next point into `out`.
    ///
    /// Returns `false` if the sequence is exhausted (after 2^64 - 1 points).
    /// This avoids the heap allocation that the `Iterator` impl requires.
    #[inline]
    pub fn next_into(&mut self, out: &mut [f64]) -> bool {
        let next_index = self.index.wrapping_add(1);
        if next_index == 0 {
            return false;
        }
        let c = next_index.trailing_zeros() as usize;
        self.index = next_index;

        for (dim, out_dim) in out.iter_mut().enumerate().take(self.dimensions) {
            self.x[dim] ^= self.directions[dim][c];
            let scrambled = self.x[dim] ^ self.scramblers[dim];
            *out_dim = ((scrambled >> 12) as f64 + 0.5) * SOBOL_POINT_SCALE;
        }

        true
    }

    /// Generate `n` points in bulk, writing sequentially into a flat buffer.
    /// `out` must have length >= `n * self.dimensions`.
    /// Returns the number of points actually written.
    #[inline]
    pub fn fill_points(&mut self, out: &mut [f64], n: usize) -> usize {
        let dims = self.dimensions;
        let mut count = 0;
        let mut offset = 0;
        while count < n && offset + dims <= out.len() {
            if !self.next_into(&mut out[offset..offset + dims]) {
                break;
            }
            offset += dims;
            count += 1;
        }
        count
    }
}

impl Iterator for SobolSequence {
    type Item = Vec<f64>;

    fn next(&mut self) -> Option<Self::Item> {
        let mut point = vec![0.0_f64; self.dimensions];
        if self.next_into(&mut point) {
            Some(point)
        } else {
            None
        }
    }
}

/// Builds the 64 direction numbers `v_j = m_j << (64 - j)` for `dim` (0-based).
///
/// Dimension 0 is the van der Corput sequence (`m_j = 1` for all `j`). Higher
/// dimensions use the Joe-Kuo initial values and the standard recurrence
/// `m_j = 2 a_1 m_(j-1) ^ 2^2 a_2 m_(j-2) ^ ... ^ 2^(s-1) a_(s-1) m_(j-s+1)
///       ^ 2^s m_(j-s) ^ m_(j-s)`.
#[inline]
fn build_direction_numbers(dim: usize) -> [u64; 64] {
    let mut v = [0_u64; 64];

    if dim == 0 {
        for (j, item) in v.iter_mut().enumerate() {
            *item = 1_u64 << (63 - j);
        }
        return v;
    }

    let (a, m_init) = JOE_KUO_D6[dim - 1];
    let s = m_init.len();

    let mut m = [0_u64; 64];
    m[..s].copy_from_slice(m_init);
    for j in s..64 {
        let mut mj = m[j - s] ^ (m[j - s] << s);
        for k in 1..s {
            if (a >> (s - 1 - k)) & 1 == 1 {
                mj ^= m[j - k] << k;
            }
        }
        m[j] = mj;
    }

    for (j, item) in v.iter_mut().enumerate() {
        *item = m[j] << (63 - j);
    }
    v
}

#[inline]
fn splitmix64(mut x: u64) -> u64 {
    x = x.wrapping_add(0x9E37_79B9_7F4A_7C15);
    x = (x ^ (x >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    x = (x ^ (x >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
    x ^ (x >> 31)
}

